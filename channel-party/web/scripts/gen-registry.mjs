// Generates web/src/generated/island-registry.ts by scanning kinds/*/web for an
// `island.manifest.json` (a map of type_id -> island entry file). Each kind's web/ dir is copied
// under src/generated/kinds/<kind>/ so the registry's dynamic imports stay inside the Astro project
// root (no cross-root Vite imports). Adding a type touches no central switch. See DESIGN §9.
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = resolve(webDir, '..');
const kindsDir = join(repoRoot, 'kinds');
const genDir = join(webDir, 'src', 'generated');
const copyDir = join(genDir, 'kinds');

await rm(copyDir, { recursive: true, force: true });
await mkdir(copyDir, { recursive: true });

const entries = [];
const kinds = existsSync(kindsDir) ? await readdir(kindsDir) : [];
for (const kind of kinds.sort()) {
  const kindWeb = join(kindsDir, kind, 'web');
  const manifestPath = join(kindWeb, 'island.manifest.json');
  if (!existsSync(manifestPath)) continue;
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  await cp(kindWeb, join(copyDir, kind), { recursive: true });
  for (const [typeId, entry] of Object.entries(manifest)) {
    const rel = String(entry).replace(/^\.\//, '');
    entries.push([typeId, `./kinds/${kind}/${rel}`]);
  }
}
entries.sort((a, b) => a[0].localeCompare(b[0]));

const lines = entries.map(
  ([typeId, path]) => `  [${JSON.stringify(typeId)}, () => import(${JSON.stringify(path)})],`,
);
const contents =
  `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit. DESIGN §9.\n` +
  `// Maps a channel/item type_id to a lazy dynamic import of its island (code-split at build).\n` +
  `export type IslandModule = {\n` +
  `  mount: (el: HTMLElement, ctx: { id: string; type_id: string }) => void;\n` +
  `};\n\n` +
  `export const islands = new Map<string, () => Promise<IslandModule>>([\n` +
  `${lines.join('\n')}\n` +
  `]);\n`;

await mkdir(genDir, { recursive: true });
await writeFile(join(genDir, 'island-registry.ts'), contents);
console.log(`gen-registry: wrote ${entries.length} island(s) to src/generated/island-registry.ts`);
